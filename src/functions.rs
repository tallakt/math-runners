/// A call of the function on sample arguments, as text of the neutral
/// syntax: the order and the first parameters small numbers, the last
/// argument `x`.
pub fn sample_call(name: &str, arity: usize) -> String {
    let args: Vec<&str> = match (name, arity) {
        ("hypergeometric", 3) => vec!["[1/2, 1]", "[3/2]", "x"],
        ("root", 2) => vec!["x", "3"],
        ("log", 2) => vec!["2", "x"],
        ("atan2", 2) => vec!["x", "2"],
        ("binomial", 2) | ("pochhammer", 2) => vec!["x", "3"],
        ("gamma", 2) | ("beta", 2) => vec!["3/2", "x"],
        ("kronecker_delta", 2) => vec!["x", "2"],
        ("lambert_w", 2) => vec!["-1", "x"],
        ("elliptic_f", 2) | ("elliptic_e", 2) => vec!["x", "1/3"],
        ("elliptic_pi", 2) => vec!["1/4", "x"],
        ("elliptic_pi", 3) => vec!["1/4", "x", "1/3"],
        ("gegenbauer_c", 3) => vec!["3", "1/2", "x"],
        ("jacobi_p", 4) => vec!["3", "1/2", "1/3", "x"],
        ("lerch_phi", 3) => vec!["x", "2", "1/2"],
        (_, 1) => vec!["x"],
        (_, 2) => vec!["2", "x"],
        (_, 3) => vec!["2", "3", "x"],
        _ => vec!["x"; arity],
    };
    format!("{name}({})", args.join(", "))
}
